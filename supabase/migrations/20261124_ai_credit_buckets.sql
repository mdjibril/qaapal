CREATE OR REPLACE FUNCTION public.refresh_ai_credit_balance(p_org_id uuid)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_now timestamptz := now();
    v_org public.organizations%ROWTYPE;
BEGIN
    UPDATE public.organizations AS org
    SET free_credits_remaining = 5,
        free_credits_reset_at = org.free_credits_reset_at
            + make_interval(
                days => (
                    floor(extract(epoch FROM (v_now - org.free_credits_reset_at)) / 604800)::integer
                    + 1
                ) * 7
            ),
        credits_balance = 5 + org.purchased_credits_remaining
    WHERE org.id = p_org_id
      AND org.free_credits_reset_at <= v_now;

    SELECT *
    INTO v_org
    FROM public.organizations
    WHERE id = p_org_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Organization not found';
    END IF;

    RETURN jsonb_build_object(
        'free_credits_remaining', v_org.free_credits_remaining,
        'purchased_credits_remaining', v_org.purchased_credits_remaining,
        'credits_balance', v_org.free_credits_remaining + v_org.purchased_credits_remaining,
        'free_credits_reset_at', v_org.free_credits_reset_at
    );
END;
$$;

CREATE OR REPLACE FUNCTION public.consume_ai_credit(p_org_id uuid)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_org public.organizations%ROWTYPE;
    v_reason text;
BEGIN
    PERFORM public.refresh_ai_credit_balance(p_org_id);

    SELECT *
    INTO v_org
    FROM public.organizations
    WHERE id = p_org_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Organization not found';
    END IF;

    IF v_org.free_credits_remaining > 0 THEN
        v_org.free_credits_remaining := v_org.free_credits_remaining - 1;
        v_reason := 'free_credit';
    ELSIF v_org.purchased_credits_remaining > 0 THEN
        v_org.purchased_credits_remaining := v_org.purchased_credits_remaining - 1;
        v_reason := 'purchased_credit';
    ELSE
        RETURN jsonb_build_object(
            'allowed', false,
            'reason', 'no_free_credits',
            'free_credits_remaining', 0,
            'purchased_credits_remaining', 0,
            'credits_balance', 0,
            'free_credits_reset_at', v_org.free_credits_reset_at
        );
    END IF;

    UPDATE public.organizations
    SET free_credits_remaining = v_org.free_credits_remaining,
        purchased_credits_remaining = v_org.purchased_credits_remaining,
        credits_balance = v_org.free_credits_remaining + v_org.purchased_credits_remaining
    WHERE id = p_org_id;

    RETURN jsonb_build_object(
        'allowed', true,
        'reason', v_reason,
        'free_credits_remaining', v_org.free_credits_remaining,
        'purchased_credits_remaining', v_org.purchased_credits_remaining,
        'credits_balance', v_org.free_credits_remaining + v_org.purchased_credits_remaining,
        'free_credits_reset_at', v_org.free_credits_reset_at
    );
END;
$$;

CREATE OR REPLACE FUNCTION public.grant_purchased_ai_credits(
    p_org_id uuid,
    p_amount integer,
    p_provider_reference text DEFAULT NULL,
    p_provider text DEFAULT 'admin',
    p_customer_email text DEFAULT NULL,
    p_product_name text DEFAULT 'Admin credit top-up',
    p_amount_paid numeric DEFAULT NULL,
    p_currency text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_transaction_id bigint;
    v_org public.organizations%ROWTYPE;
    v_existing_transaction public.payment_transactions%ROWTYPE;
BEGIN
    IF p_amount IS NULL OR p_amount NOT IN (20, 150, 400) THEN
        RAISE EXCEPTION 'Unsupported credit pack amount';
    END IF;

    IF p_provider_reference IS NOT NULL THEN
        IF NULLIF(trim(p_provider_reference), '') IS NULL
           OR NULLIF(trim(p_customer_email), '') IS NULL THEN
            RAISE EXCEPTION 'Payment reference and customer email are required';
        END IF;

        INSERT INTO public.payment_transactions (
            provider,
            provider_reference,
            org_id,
            customer_email,
            product_name,
            amount_paid,
            currency,
            credits_applied
        )
        VALUES (
            p_provider,
            trim(p_provider_reference),
            p_org_id,
            lower(trim(p_customer_email)),
            p_product_name,
            p_amount_paid,
            p_currency,
            p_amount
        )
        ON CONFLICT (provider, provider_reference) DO NOTHING
        RETURNING id INTO v_transaction_id;

        IF v_transaction_id IS NULL THEN
            SELECT *
            INTO v_existing_transaction
            FROM public.payment_transactions
            WHERE provider = p_provider
              AND provider_reference = trim(p_provider_reference);

            IF NOT FOUND
               OR v_existing_transaction.org_id <> p_org_id
               OR v_existing_transaction.credits_applied <> p_amount THEN
                RAISE EXCEPTION 'Payment reference conflicts with an existing transaction';
            END IF;

            RETURN jsonb_build_object('status', 'duplicate');
        END IF;
    END IF;

    UPDATE public.organizations
    SET purchased_credits_remaining = purchased_credits_remaining + p_amount,
        ai_credits_purchased = COALESCE(ai_credits_purchased, 0) + p_amount,
        credits_balance = free_credits_remaining + purchased_credits_remaining + p_amount
    WHERE id = p_org_id
    RETURNING * INTO v_org;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Organization not found';
    END IF;

    RETURN jsonb_build_object(
        'status', 'applied',
        'free_credits_remaining', v_org.free_credits_remaining,
        'purchased_credits_remaining', v_org.purchased_credits_remaining,
        'credits_balance', v_org.free_credits_remaining + v_org.purchased_credits_remaining,
        'free_credits_reset_at', v_org.free_credits_reset_at
    );
END;
$$;

CREATE OR REPLACE FUNCTION public.set_ai_credit_balance(p_org_id uuid, p_balance integer)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
    IF p_balance IS NULL OR p_balance < 0 THEN
        RAISE EXCEPTION 'Credit balance cannot be negative';
    END IF;

    UPDATE public.organizations
    SET free_credits_remaining = LEAST(p_balance, 5),
        purchased_credits_remaining = GREATEST(p_balance - 5, 0),
        credits_balance = p_balance
    WHERE id = p_org_id;

    RETURN FOUND;
END;
$$;

CREATE OR REPLACE FUNCTION public.set_org_subscription_tier(
    p_org_id uuid,
    p_new_tier public.subscription_tier
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
    UPDATE public.organizations
    SET subscription_tier = p_new_tier,
        subscription_start_date = now(),
        free_credits_remaining = CASE
            WHEN p_new_tier = 'free' THEN 5
            ELSE free_credits_remaining
        END,
        free_credits_reset_at = CASE
            WHEN p_new_tier = 'free' THEN now() + interval '7 days'
            ELSE free_credits_reset_at
        END,
        credits_balance = CASE
            WHEN p_new_tier = 'free' THEN 5 + purchased_credits_remaining
            ELSE credits_balance
        END
    WHERE id = p_org_id;

    RETURN FOUND;
END;
$$;

