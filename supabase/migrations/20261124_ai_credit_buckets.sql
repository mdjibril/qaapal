-- Separate the renewable free allowance from purchased report credits.
ALTER TABLE public.organizations
    ADD COLUMN IF NOT EXISTS free_credits_remaining integer,
    ADD COLUMN IF NOT EXISTS free_credits_reset_at timestamptz,
    ADD COLUMN IF NOT EXISTS purchased_credits_remaining integer;

-- Preserve each organization's current visible balance. Since the old balance
-- mixed free and purchased credits, assign up to five to the free bucket and
-- carry the remainder as purchased credits.
UPDATE public.organizations
SET credits_balance = GREATEST(COALESCE(credits_balance, 0), 0),
    free_credits_remaining = LEAST(GREATEST(COALESCE(credits_balance, 0), 0), 5),
    purchased_credits_remaining = GREATEST(COALESCE(credits_balance, 0) - 5, 0),
    free_credits_reset_at = now() + interval '7 days'
WHERE free_credits_remaining IS NULL
   OR purchased_credits_remaining IS NULL
   OR free_credits_reset_at IS NULL;

ALTER TABLE public.organizations
    ALTER COLUMN free_credits_remaining SET DEFAULT 5,
    ALTER COLUMN free_credits_remaining SET NOT NULL,
    ALTER COLUMN free_credits_reset_at SET DEFAULT (now() + interval '7 days'),
    ALTER COLUMN free_credits_reset_at SET NOT NULL,
    ALTER COLUMN purchased_credits_remaining SET DEFAULT 0,
    ALTER COLUMN purchased_credits_remaining SET NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'organizations_free_credits_remaining_nonnegative'
    ) THEN
        ALTER TABLE public.organizations
            ADD CONSTRAINT organizations_free_credits_remaining_nonnegative
            CHECK (free_credits_remaining >= 0);
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'organizations_purchased_credits_remaining_nonnegative'
    ) THEN
        ALTER TABLE public.organizations
            ADD CONSTRAINT organizations_purchased_credits_remaining_nonnegative
            CHECK (purchased_credits_remaining >= 0);
    END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS public.payment_transactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider text NOT NULL,
    provider_reference text NOT NULL,
    org_id uuid NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
    customer_email text NOT NULL,
    product_name text NOT NULL,
    amount_paid numeric(12, 2),
    currency text,
    credits_applied integer NOT NULL CHECK (credits_applied > 0),
    status text NOT NULL DEFAULT 'completed',
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (provider, provider_reference)
);

