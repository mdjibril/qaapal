CREATE TABLE public.witness_statements (
    id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
    created_at timestamptz DEFAULT now(),
    witness_name text NOT NULL CHECK (char_length(witness_name) <= 150),
    witness_role text CHECK (char_length(witness_role) <= 150),
    candidate_name text NOT NULL CHECK (char_length(candidate_name) <= 150),
    trade_id bigint REFERENCES public.trades(id) ON DELETE SET NULL,
    unit_codes text,
    witness_notes text CHECK (char_length(witness_notes) <= 2500),
    statement_text text CHECK (char_length(statement_text) > 0),
    created_by uuid REFERENCES public.user_profiles(id) ON DELETE SET NULL
