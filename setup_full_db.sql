    report_text text CHECK (char_length(report_text) > 0),
    assessment_date text,
    created_at timestamptz DEFAULT now(),
    created_by uuid REFERENCES public.user_profiles(id) ON DELETE SET NULL
);

CREATE TABLE public.student_statements (
    id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
    created_at timestamptz DEFAULT now(),
    user_id uuid REFERENCES public.user_profiles(id) ON DELETE CASCADE,
    student_name text NOT NULL CHECK (char_length(student_name) <= 150),
    trade_id bigint REFERENCES public.trades(id) ON DELETE SET NULL,
    unit_codes text,
    reflection_notes text CHECK (char_length(reflection_notes) <= 2500),
    statement_text text CHECK (char_length(statement_text) > 0),
    created_by uuid REFERENCES public.user_profiles(id) ON DELETE SET NULL
