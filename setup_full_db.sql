-- 6. Security Hardening

-- 6.1 Automation: New User Trigger Logic
-- This function runs every time a user signs up in Supabase Auth.
CREATE OR REPLACE FUNCTION public.handle_new_user_setup()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    new_org_id uuid;
    org_name_val text;
BEGIN
    -- Extract the organization name from the metadata provided in auth_utils.py
    org_name_val := COALESCE(new.raw_user_meta_data->>'org_name', 'Personal Workspace');

    -- 1. Create the organization for the new user with 10 free credits
    INSERT INTO public.organizations (name, subscription_tier, credits_balance)
    VALUES (org_name_val, 'free', 5)
    RETURNING id INTO new_org_id;

    -- 2. Create the user profile linked to the new organization
    INSERT INTO public.user_profiles (
        id, 
        email, 
        full_name, 
        org_id, 
        org_role,
        marketing_source,
        primary_trade,
        monthly_report_volume
    )
    VALUES (
        new.id, 
        new.email, 
        new.raw_user_meta_data->>'full_name', 
        new_org_id, 
        'admin',
        new.raw_user_meta_data->>'marketing_source',
        new.raw_user_meta_data->>'primary_trade',
        new.raw_user_meta_data->>'monthly_volume'
    );

    RETURN new;
END;
$$;

-- Create the trigger on auth.users
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user_setup();

-- Set search_path and revoke public execute for security definer functions
-- to prevent search-path hijacking and unauthorized API access.

ALTER FUNCTION public.handle_new_user_setup() SET search_path = public;
REVOKE EXECUTE ON FUNCTION public.handle_new_user_setup() FROM PUBLIC;

ALTER FUNCTION public.rls_auto_enable() SET search_path = public;
REVOKE EXECUTE ON FUNCTION public.rls_auto_enable() FROM PUBLIC;

-- 6.2 Auto-Renew Free Credits Logic
-- Trigger to record when an organization's credit drops to zero
CREATE OR REPLACE FUNCTION public.handle_credit_depletion()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    -- If credit hits zero, record the timestamp
    IF NEW.credits_balance = 0 AND OLD.credits_balance > 0 THEN
        NEW.last_credit_depletion = now();
    -- If credit is manually topped up, clear the timestamp
    ELSIF NEW.credits_balance > 0 THEN
        NEW.last_credit_depletion = NULL;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_credit_update ON public.organizations;
CREATE TRIGGER on_credit_update
  BEFORE UPDATE ON public.organizations
  FOR EACH ROW EXECUTE FUNCTION public.handle_credit_depletion();

