ALTER TABLE IF EXISTS public.user_profiles 
DROP CONSTRAINT IF EXISTS user_profiles_role_check;
ALTER TABLE IF EXISTS public.user_profiles 
ADD CONSTRAINT user_profiles_role_check CHECK (role IN ('admin', 'assessor', 'student'));

-- Add assessor_role if it doesn't already exist (migration-safe)
ALTER TABLE IF EXISTS public.user_profiles
ADD COLUMN IF NOT EXISTS assessor_role text DEFAULT NULL;
ALTER TABLE IF EXISTS public.user_profiles
DROP CONSTRAINT IF EXISTS user_profiles_assessor_role_check;
ALTER TABLE IF EXISTS public.user_profiles
ADD CONSTRAINT user_profiles_assessor_role_check CHECK (assessor_role IN ('QAA', 'IQA', 'EQA') OR assessor_role IS NULL);

-- 2. NSQ Structure (NOS)
CREATE TABLE public.trades (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
    name text NOT NULL
);

CREATE TABLE public.trade_levels (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_id bigint NOT NULL REFERENCES public.trades(id) ON DELETE CASCADE,
    level int NOT NULL,
    display_name text,
    source_file text,
    created_at timestamptz DEFAULT now(),
    updated_at timestamptz DEFAULT now(),
    CONSTRAINT trade_levels_trade_id_level_key UNIQUE (trade_id, level)
);

CREATE TABLE public.units (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
    trade_id bigint REFERENCES public.trades(id) ON DELETE CASCADE, 
    trade_level_id bigint REFERENCES public.trade_levels(id) ON DELETE SET NULL,
    code text NOT NULL, 
    title text NOT NULL
);

CREATE TABLE public.learning_outcomes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
    unit_id bigint REFERENCES public.units(id) ON DELETE CASCADE, 
    lo_num text NOT NULL, 
    description text NOT NULL
);

CREATE TABLE public.performance_criteria (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
    lo_id bigint REFERENCES public.learning_outcomes(id) ON DELETE CASCADE, 
    pc_code text NOT NULL, 
    description text NOT NULL
);

-- 3. Assessment & Evidence Reporting
